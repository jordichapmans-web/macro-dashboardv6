export function sectorScoreBandExplanation(score: number): string {
  if (score >= 80) return "Strongly favored by the current macro regime and real-time sector drivers.";
  if (score >= 65) return "Favored by the current macro regime, with supportive sector drivers.";
  if (score >= 45) return "Roughly neutral — mixed signals from the current regime and sector drivers.";
  return "Not favored by the current macro regime right now.";
}

